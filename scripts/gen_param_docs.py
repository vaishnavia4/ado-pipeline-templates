"""Generate docs/parameters.md from the `parameters:` blocks of every template.

Each parameter is documented by the comment line directly above its `- name:` entry.

Usage:
    python scripts/gen_param_docs.py          # rewrite docs/parameters.md
    python scripts/gen_param_docs.py --check  # exit 1 if the file is out of date
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE_DIRS = ("stages", "jobs", "steps", "pipelines")
OUTPUT = ROOT / "docs" / "parameters.md"

NAME_RE = re.compile(r"^  - name: (\S+)\s*$")
KEY_RE = re.compile(r"^    (type|default|values): ?(.*)$")


@dataclass
class Param:
    name: str
    description: str = ""
    type: str = "string"
    default: str | None = None
    values: list[str] = field(default_factory=list)


def template_files() -> list[Path]:
    files: list[Path] = []
    for folder in TEMPLATE_DIRS:
        files.extend(sorted((ROOT / "templates" / folder).glob("*.yml")))
    return files


def parse_parameters(path: Path) -> tuple[str, list[Param]]:
    """Return (header comment, parameters) for one template file."""
    lines = path.read_text(encoding="utf-8").splitlines()
    header = lines[0].lstrip("# ").strip() if lines and lines[0].startswith("#") else ""
    params: list[Param] = []
    try:
        start = lines.index("parameters:") + 1
    except ValueError:
        return header, params

    pending_comment = ""
    current: Param | None = None
    section = ""  # which multi-line key we are inside (default or values)
    for line in lines[start:]:
        if line and not line.startswith(" "):
            break  # next top-level key
        stripped = line.strip()
        if stripped.startswith("#") and line.startswith("  #"):
            pending_comment = stripped.lstrip("# ").strip()
            continue
        match = NAME_RE.match(line)
        if match:
            current = Param(name=match.group(1), description=pending_comment)
            params.append(current)
            pending_comment = ""
            section = ""
            continue
        if current is None:
            continue
        key = KEY_RE.match(line)
        if key:
            name, value = key.group(1), key.group(2).strip()
            section = name
            if name == "type":
                current.type = value
            elif name == "default":
                current.default = value if value else ""
                if not value:
                    current.default = None
                    section = "default-block"
            elif name == "values":
                section = "values"
            continue
        if section == "values" and stripped.startswith("- "):
            current.values.append(stripped[2:].strip())
        elif section == "default-block" and stripped:
            # Multi-line default (object): collapse to a compact one-liner.
            piece = stripped.lstrip("- ")
            current.default = f"{current.default} {piece}".strip() if current.default else "{ " + piece
    # Close collapsed object defaults.
    for param in params:
        if param.default and param.default.startswith("{ "):
            param.default += " }"
    return header, params


def format_default(param: Param) -> str:
    if param.default is None:
        return "required"
    if param.default in ("", "''"):
        return "`''`"
    return f"`{param.default}`"


def render() -> str:
    out: list[str] = [
        "# Parameter reference",
        "",
        "Generated by `python scripts/gen_param_docs.py` from the comments above each parameter.",
        "Do not edit by hand: change the template comment and regenerate.",
        "",
    ]
    for path in template_files():
        header, params = parse_parameters(path)
        rel = path.relative_to(ROOT / "templates").as_posix()
        out.append(f"## {rel}")
        out.append("")
        if header:
            out.append(header)
            out.append("")
        if not params:
            out.append("No parameters.")
            out.append("")
            continue
        out.append("| Parameter | Type | Default | Description |")
        out.append("| --- | --- | --- | --- |")
        for param in params:
            description = param.description
            if param.values:
                description += " Allowed: " + ", ".join(f"`{v}`" for v in param.values) + "."
            out.append(f"| `{param.name}` | {param.type} | {format_default(param)} | {description} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print("docs/parameters.md is out of date. Run: python scripts/gen_param_docs.py")
            return 1
        print("docs/parameters.md is up to date.")
        return 0
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
